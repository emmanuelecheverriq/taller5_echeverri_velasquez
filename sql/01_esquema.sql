-- ============================================================================
-- 01_esquema.sql  |  Creacion del esquema relacional (PostgreSQL 14 o superior)
-- Proyecto: Registro de paros de produccion - lineas de envasado Vinilos_1 a Vinilos_4
-- Ejecutar conectado a la base de datos bdi_paros (ver 00_crear_base.sql).
-- El script se puede ejecutar varias veces: empieza borrando lo que haya creado antes.
-- ============================================================================

DROP SCHEMA IF EXISTS privado CASCADE;
DROP SCHEMA IF EXISTS paros CASCADE;

CREATE SCHEMA paros;     -- datos de negocio (catalogos, registros, paros)
CREATE SCHEMA privado;   -- datos personales (identidad real del personal), acceso restringido

SET search_path TO paros, public;

-- ----------------------------------------------------------------------------
-- CATALOGOS
-- ----------------------------------------------------------------------------

-- Lineas de envasado
CREATE TABLE maquina (
    id_maquina  SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(20) NOT NULL,
    activa      BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_maquina        PRIMARY KEY (id_maquina),
    CONSTRAINT uq_maquina_nombre UNIQUE (nombre)
);

-- Turnos de trabajo (el Excel los escribia de 8 formas distintas)
CREATE TABLE turno (
    id_turno     SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR(30) NOT NULL,
    hora_inicio  TIME,
    hora_fin     TIME,
    CONSTRAINT pk_turno        PRIMARY KEY (id_turno),
    CONSTRAINT uq_turno_nombre UNIQUE (nombre),
    -- si se conoce una hora de la jornada se conocen las dos
    CONSTRAINT ck_turno_horas  CHECK ((hora_inicio IS NULL) = (hora_fin IS NULL))
);

-- Areas de la empresa a las que impacta un codigo de paro
CREATE TABLE area_impacto (
    id_area  SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre   VARCHAR(40) NOT NULL,
    CONSTRAINT pk_area_impacto        PRIMARY KEY (id_area),
    CONSTRAINT uq_area_impacto_nombre UNIQUE (nombre)
);

-- Codigos de paro 01 a 18 (el id ES el codigo de negocio, por eso no es autoincremental)
CREATE TABLE codigo_paro (
    id_codigo_paro  SMALLINT     NOT NULL,
    nombre          VARCHAR(100) NOT NULL,
    id_area         SMALLINT,
    CONSTRAINT pk_codigo_paro        PRIMARY KEY (id_codigo_paro),
    CONSTRAINT uq_codigo_paro_nombre UNIQUE (nombre),
    CONSTRAINT ck_codigo_paro_rango  CHECK (id_codigo_paro BETWEEN 1 AND 99),
    CONSTRAINT fk_codigo_paro_area   FOREIGN KEY (id_area)
        REFERENCES area_impacto (id_area) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Subcodigos de un codigo de paro. Jerarquia de dos niveles:
--   nivel 1 = sistema de la maquina (ej. 1.2 Sistema de dosificacion)
--   nivel 2 = componente (ej. 1.2.B Ajuste de sensor), con id_subcodigo_padre = el sistema
CREATE TABLE subcodigo_paro (
    id_subcodigo        SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    id_codigo_paro      SMALLINT     NOT NULL,
    codigo_sub          VARCHAR(10)  NOT NULL,
    descripcion         VARCHAR(100) NOT NULL,
    id_subcodigo_padre  SMALLINT,
    nivel               SMALLINT     NOT NULL,
    CONSTRAINT pk_subcodigo_paro      PRIMARY KEY (id_subcodigo),
    CONSTRAINT uq_subcodigo_codigo    UNIQUE (id_codigo_paro, codigo_sub),
    -- necesaria para la llave foranea compuesta desde paro (garantiza que el subcodigo pertenece al codigo)
    CONSTRAINT uq_subcodigo_pertenece UNIQUE (id_subcodigo, id_codigo_paro),
    CONSTRAINT ck_subcodigo_nivel     CHECK (nivel IN (1, 2)),
    CONSTRAINT ck_subcodigo_jerarquia CHECK ((nivel = 1 AND id_subcodigo_padre IS NULL)
                                          OR (nivel = 2 AND id_subcodigo_padre IS NOT NULL)),
    CONSTRAINT fk_subcodigo_codigo    FOREIGN KEY (id_codigo_paro)
        REFERENCES codigo_paro (id_codigo_paro) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_subcodigo_padre     FOREIGN KEY (id_subcodigo_padre)
        REFERENCES subcodigo_paro (id_subcodigo) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Tabla de homologacion usada en la migracion: texto escrito en el Excel -> subcodigo canonico
CREATE TABLE equivalencia_subcodigo (
    texto_origen  VARCHAR(120) NOT NULL,
    id_subcodigo  SMALLINT     NOT NULL,
    CONSTRAINT pk_equivalencia_subcodigo PRIMARY KEY (texto_origen),
    CONSTRAINT fk_equivalencia_subcodigo FOREIGN KEY (id_subcodigo)
        REFERENCES subcodigo_paro (id_subcodigo) ON DELETE CASCADE ON UPDATE CASCADE
);

-- Motivos de parada de maquina (campo "Tipo de paro" del Excel). Conviven dos numeraciones:
--   ANTERIOR (2022-2023, ej. "17. PARO DE MAQUINA") y ACTUAL (desde 2024, ej. "[18] Paro de maquina por ventas")
CREATE TABLE motivo_parada (
    id_motivo             SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    sistema_codificacion  VARCHAR(10)  NOT NULL,
    codigo                SMALLINT     NOT NULL,
    nombre                VARCHAR(120) NOT NULL,
    CONSTRAINT pk_motivo_parada    PRIMARY KEY (id_motivo),
    CONSTRAINT uq_motivo_parada    UNIQUE (sistema_codificacion, codigo),
    CONSTRAINT ck_motivo_sistema   CHECK (sistema_codificacion IN ('ANTERIOR', 'ACTUAL')),
    CONSTRAINT ck_motivo_codigo    CHECK (codigo > 0)
);

-- Productos que se envasan (referencia = marca + volumen + numero de colores)
CREATE TABLE referencia (
    id_referencia  SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR(60) NOT NULL,
    marca          VARCHAR(50) NOT NULL,
    volumen_cc     SMALLINT,
    num_colores    SMALLINT,
    CONSTRAINT pk_referencia        PRIMARY KEY (id_referencia),
    CONSTRAINT uq_referencia_nombre UNIQUE (nombre),
    CONSTRAINT ck_referencia_vol    CHECK (volumen_cc IS NULL OR volumen_cc > 0),
    CONSTRAINT ck_referencia_col    CHECK (num_colores IS NULL OR num_colores > 0)
);

-- Personal (operarias/os y tecnicos de mantenimiento) identificado SOLO por seudonimo
CREATE TABLE persona (
    id_persona        SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    codigo_seudonimo  VARCHAR(10) NOT NULL,
    tipo_persona      VARCHAR(13) NOT NULL,
    activa            BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_persona        PRIMARY KEY (id_persona),
    CONSTRAINT uq_persona_codigo UNIQUE (codigo_seudonimo),
    CONSTRAINT ck_persona_tipo   CHECK (tipo_persona IN ('OPERARIO', 'MANTENIMIENTO'))
);

-- Identidad real: esquema aparte con permisos restringidos (ver 06_seguridad.sql y docs/07_datos_personales.md)
CREATE TABLE privado.persona_identidad (
    id_persona       SMALLINT     NOT NULL,
    nombre_completo  VARCHAR(120) NOT NULL,
    fecha_carga      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_persona_identidad PRIMARY KEY (id_persona),
    CONSTRAINT fk_persona_identidad FOREIGN KEY (id_persona)
        REFERENCES paros.persona (id_persona) ON DELETE CASCADE ON UPDATE CASCADE
);

-- ----------------------------------------------------------------------------
-- TABLAS TRANSACCIONALES
-- ----------------------------------------------------------------------------

-- Un registro = lo que una operaria anota para una maquina, un turno y una referencia
-- (una fila "principal" del formato hora a hora).
CREATE TABLE registro_produccion (
    id_registro       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fecha             DATE         NOT NULL,
    id_maquina        SMALLINT     NOT NULL,
    id_turno          SMALLINT     NOT NULL,
    secuencia         SMALLINT     NOT NULL DEFAULT 1,   -- 1, 2, 3... si en el mismo turno hay varios registros
    id_persona        SMALLINT,                          -- NULL = operaria no registrada (datos de 2022-2023)
    id_referencia     SMALLINT,                          -- NULL = referencia no registrada
    pacas_producidas  INTEGER      NOT NULL DEFAULT 0,
    horas_trabajadas  NUMERIC(5,2) NOT NULL DEFAULT 0,
    es_sintetico      BOOLEAN      NOT NULL DEFAULT FALSE, -- TRUE = creado en la migracion para conservar paros sin registro principal
    observaciones     VARCHAR(500),
    CONSTRAINT pk_registro_produccion PRIMARY KEY (id_registro),
    CONSTRAINT uq_registro_negocio    UNIQUE (fecha, id_maquina, id_turno, secuencia),
    CONSTRAINT ck_registro_fecha      CHECK (fecha >= '2020-01-01'),
    CONSTRAINT ck_registro_secuencia  CHECK (secuencia >= 1),
    CONSTRAINT ck_registro_pacas      CHECK (pacas_producidas >= 0),
    CONSTRAINT ck_registro_horas      CHECK (horas_trabajadas >= 0 AND horas_trabajadas <= 24),
    CONSTRAINT ck_registro_sintetico  CHECK (NOT es_sintetico OR (pacas_producidas = 0 AND horas_trabajadas = 0)),
    CONSTRAINT fk_registro_maquina    FOREIGN KEY (id_maquina)    REFERENCES maquina (id_maquina)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_registro_turno      FOREIGN KEY (id_turno)      REFERENCES turno (id_turno)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_registro_persona    FOREIGN KEY (id_persona)    REFERENCES persona (id_persona)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT fk_registro_referencia FOREIGN KEY (id_referencia) REFERENCES referencia (id_referencia)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Un paro = tiempo perdido por un codigo (y opcionalmente un subcodigo) dentro de un registro.
-- Reemplaza las 18 columnas "Codigo de paro n" / "Codigo n en horas" del Excel (grupo repetitivo).
CREATE TABLE paro (
    id_paro          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_registro      INTEGER      NOT NULL,
    id_codigo_paro   SMALLINT     NOT NULL,
    id_subcodigo     SMALLINT,
    minutos          NUMERIC(7,2) NOT NULL,
    equipo_ejecutor  VARCHAR(13),     -- quien realizo el ajuste (solo se registra para el codigo 05)
    id_persona       SMALLINT,        -- persona involucrada (seudonimo)
    CONSTRAINT pk_paro            PRIMARY KEY (id_paro),
    CONSTRAINT ck_paro_minutos    CHECK (minutos > 0 AND minutos <= 1440),
    CONSTRAINT ck_paro_equipo     CHECK (equipo_ejecutor IS NULL OR equipo_ejecutor IN ('OPERARIOS', 'MANTENIMIENTO')),
    CONSTRAINT fk_paro_registro   FOREIGN KEY (id_registro)    REFERENCES registro_produccion (id_registro)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_paro_codigo     FOREIGN KEY (id_codigo_paro) REFERENCES codigo_paro (id_codigo_paro)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    -- llave compuesta: el subcodigo debe pertenecer al codigo indicado (si id_subcodigo es NULL no se valida)
    CONSTRAINT fk_paro_subcodigo  FOREIGN KEY (id_subcodigo, id_codigo_paro)
        REFERENCES subcodigo_paro (id_subcodigo, id_codigo_paro) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_paro_persona    FOREIGN KEY (id_persona)     REFERENCES persona (id_persona)
        ON DELETE SET NULL ON UPDATE CASCADE
);

-- Parada de maquina: horas del dia en que la maquina no se programo / no trabajo y por que
-- (columnas "Horas no trabajadas", "Tipo de paro" y "Observaciones de paro" del Excel).
CREATE TABLE parada_maquina (
    id_parada            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    fecha                DATE         NOT NULL,
    id_maquina           SMALLINT     NOT NULL,
    id_motivo            SMALLINT     NOT NULL,
    horas_no_trabajadas  NUMERIC(5,2) NOT NULL,
    observacion          VARCHAR(200),
    CONSTRAINT pk_parada_maquina  PRIMARY KEY (id_parada),
    CONSTRAINT ck_parada_fecha    CHECK (fecha >= '2020-01-01'),
    CONSTRAINT ck_parada_horas    CHECK (horas_no_trabajadas > 0 AND horas_no_trabajadas <= 48),
    CONSTRAINT fk_parada_maquina  FOREIGN KEY (id_maquina) REFERENCES maquina (id_maquina)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_parada_motivo   FOREIGN KEY (id_motivo)  REFERENCES motivo_parada (id_motivo)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

COMMENT ON TABLE registro_produccion IS 'Un registro por maquina, turno y referencia (fila principal del formato hora a hora).';
COMMENT ON TABLE paro               IS 'Tiempo perdido por codigo/subcodigo dentro de un registro (reemplaza las 18 columnas de codigos del Excel).';
COMMENT ON TABLE parada_maquina     IS 'Horas del dia que la maquina no trabajo y el motivo.';
COMMENT ON TABLE persona            IS 'Personal seudonimizado. La identidad real esta en privado.persona_identidad.';
